#!/usr/bin/env bash
# Install the network traffic filter's nginx side.
#
# Called by monitor.service through a single NOPASSWD sudoers rule:
#
#     monsvc ALL=(root) NOPASSWD: /usr/local/libexec/monitor-nginx-tf
#
# The unprivileged service writes three files into /var/lib/monitor/nginx/
# (mode, tf-80.map, tf-443.map) plus index.html for the failure page. This
# script validates every byte before anything reaches nginx:
#
#   - mode must be exactly drop, 404 or redirect;
#   - each map line must be "<cidr> 1;" and parses as an IPv4/IPv6 network
#     (a /0 is refused; a broken or injected line aborts the whole sync);
#   - the failure page must be valid UTF-8 under the size cap.
#
# Only the two map files are copied as nginx `include` targets; they hold plain
# CIDR lines, never directives. Everything else is generated here from fixed
# templates, so a compromised service cannot inject configuration. The failure
# page is a static file served by its own vhost (blocked.example.com), not part of
# any directive either.
#
# Exit codes: 0 ok (or nothing changed), 1 validation/setup error,
# 2 nginx -t / reload failed (previous files restored, nginx left as it was).
set -euo pipefail

STAGE=/var/lib/monitor/nginx
CONF_D=/etc/nginx/conf.d
SNIPPETS=/etc/nginx/snippets
WWW=/var/www/blocked.example.com
LOCK=/run/monitor-nginx-tf.lock
MAX_MAP_LINES=80000
MAX_MAP_BYTES=2097152
MAX_HTML_BYTES=$((200 * 1024))

exec 9>"$LOCK"
flock -n 9 || { echo "monitor-nginx-tf: another sync is already running" >&2; exit 1; }

WORK="$(mktemp -d "${TMPDIR:-/tmp}/monitor-nginx-tf.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK/backup" "$WORK/out"

die() { echo "monitor-nginx-tf: $*" >&2; exit 1; }

[ -d "$STAGE" ] || die "missing staging directory $STAGE"
MODE="$(cat "$STAGE/mode" 2>/dev/null || true)"
case "$MODE" in
  drop|404|redirect) ;;
  *) die "invalid mode: '$MODE'" ;;
esac

clean_map() {
  local src="$1" dst="$2" bytes lines
  [ -f "$src" ] && [ ! -L "$src" ] || die "bad staging file $src"
  bytes=$(stat -c %s "$src")
  [ "$bytes" -le "$MAX_MAP_BYTES" ] || die "$src is larger than ${MAX_MAP_BYTES} bytes"
  lines=$(wc -l < "$src")
  [ "$lines" -le "$MAX_MAP_LINES" ] || die "$src has more than ${MAX_MAP_LINES} lines"
  python3 - "$src" "$dst" <<'PY'
import ipaddress
import sys

src, dst = sys.argv[1], sys.argv[2]
out = set()
try:
    fh = open(src, 'r', encoding='utf-8', errors='strict')
except Exception as exc:  # noqa: BLE001 - report and abort
    raise SystemExit(f'monitor-nginx-tf: cannot read {src}: {exc}')
with fh:
    for lineno, raw in enumerate(fh, 1):
        line = raw.strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) != 2 or parts[1] != '1;':
            raise SystemExit(f'monitor-nginx-tf: {src}:{lineno}: expected "<cidr> 1;"')
        try:
            net = ipaddress.ip_network(parts[0], strict=False)
        except ValueError as exc:
            raise SystemExit(f'monitor-nginx-tf: {src}:{lineno}: {exc}')
        if net.prefixlen == 0:
            raise SystemExit(f'monitor-nginx-tf: {src}:{lineno}: /0 is refused')
        out.add(f'{net.with_prefixlen} 1;')
with open(dst, 'w', encoding='ascii') as fh:
    for line in sorted(out):
        fh.write(line + '\n')
PY
}

clean_html() {
  local src="$1" dst="$2" bytes
  [ -f "$src" ] && [ ! -L "$src" ] || die "bad staging file $src"
  bytes=$(stat -c %s "$src")
  [ "$bytes" -le "$MAX_HTML_BYTES" ] || die "$src is larger than ${MAX_HTML_BYTES} bytes"
  python3 - "$src" "$dst" <<'PY'
import sys

src, dst = sys.argv[1], sys.argv[2]
data = open(src, 'rb').read()
if b'\x00' in data:
    raise SystemExit(f'monitor-nginx-tf: {src}: NUL byte in HTML')
try:
    data.decode('utf-8', errors='strict')
except UnicodeDecodeError as exc:
    raise SystemExit(f'monitor-nginx-tf: {src}: not valid UTF-8: {exc}')
open(dst, 'wb').write(data)
PY
}

clean_map "$STAGE/cf.map" "$WORK/out/cf.map"
clean_map "$STAGE/tf-exempt.map" "$WORK/out/tf-exempt.map"
clean_map "$STAGE/tf-80.map" "$WORK/out/tf-80.map"
clean_map "$STAGE/tf-443.map" "$WORK/out/tf-443.map"
clean_html "$STAGE/index.html" "$WORK/out/index.html"

# Behind Cloudflare, nginx sees the edge address unless the visitor is restored
# from CF-Connecting-IP. Only the ranges staged above are trusted, so direct
# clients cannot spoof that header and skip a rule.
realip_block() {
  [ -s "$WORK/out/cf.map" ] || return 0
  echo "# Restore the visitor address; trust CF-Connecting-IP only from these networks."
  while read -r cidr _; do
    [ -n "$cidr" ] && echo "set_real_ip_from $cidr;"
  done < "$WORK/out/cf.map"
  echo "real_ip_header CF-Connecting-IP;"
}

# --- generated configuration -------------------------------------------------

cat > "$WORK/out/monitor-traffic-filter.conf" <<'EOF'
# Generated by /usr/local/libexec/monitor-nginx-tf from the panel's
# "network traffic filter" settings. Do not edit by hand — the monitor
# rewrites this file on every rule change.
geo $tf_block80 {
    default 0;
    include /etc/nginx/conf.d/monitor-tf-80.map;
}

geo $tf_block443 {
    default 0;
    include /etc/nginx/conf.d/monitor-tf-443.map;
}

geo $tf_exempt {
    default 0;
    include /etc/nginx/conf.d/monitor-tf-exempt.map;
}

geo $realip_remote_addr $tf_from_cf {
    default 0;
    include /etc/nginx/conf.d/monitor-tf-cf.map;
}

# Trust CF-IPCountry only when the request really came from Cloudflare. A
# direct client could otherwise send "CF-IPCountry: US" and skip a country
# rule. This also catches mainland visitors whose address is missing from the
# ipdeny zone file, which is refreshed daily but not authoritative.
map "$tf_from_cf:$http_cf_ipcountry" $tf_cf_country {
    default 0;
    "1:CN" 1;
}
EOF

if [ "$MODE" != drop ]; then
  cat >> "$WORK/out/monitor-traffic-filter.conf" <<EOF
map "\$tf_block80:\$tf_cf_country:\$tf_exempt" \$tf_action80 {
    default "";
    "1:0:0" $MODE;
    "0:1:0" $MODE;
    "1:1:0" $MODE;
}

map "\$tf_block443:\$tf_cf_country:\$tf_exempt" \$tf_action443 {
    default "";
    "1:0:0" $MODE;
    "0:1:0" $MODE;
    "1:1:0" $MODE;
}
EOF
fi

{
  echo "# Generated by /usr/local/libexec/monitor-nginx-tf. mode=$MODE"
  realip_block
  case "$MODE" in
    404) echo 'if ($tf_action80 = 404) { return 404; }' ;;
    redirect) echo 'if ($tf_action80 = redirect) { return 302 https://blocked.example.com/; }' ;;
  esac
} > "$WORK/out/monitor-tf-80.conf"

{
  echo "# Generated by /usr/local/libexec/monitor-nginx-tf. mode=$MODE"
  realip_block
  case "$MODE" in
    404) echo 'if ($tf_action443 = 404) { return 404; }' ;;
    redirect) echo 'if ($tf_action443 = redirect) { return 302 https://blocked.example.com/; }' ;;
  esac
} > "$WORK/out/monitor-tf-443.conf"

# --- install with rollback ---------------------------------------------------

install -d -o root -g root -m 755 "$WWW"

FILES=(
  "$CONF_D/monitor-traffic-filter.conf"
  "$CONF_D/monitor-tf-80.map"
  "$CONF_D/monitor-tf-443.map"
  "$CONF_D/monitor-tf-cf.map"
  "$CONF_D/monitor-tf-exempt.map"
  "$SNIPPETS/monitor-tf-80.conf"
  "$SNIPPETS/monitor-tf-443.conf"
  "$WWW/index.html"
)

changed=0
backup_of() { printf '%s/backup/%s' "$WORK" "$(printf '%s' "$1" | tr '/' '_')"; }

install_one() {
  local src="$1" dst="$2" key
  key=$(backup_of "$dst")
  if [ -f "$dst" ] && cmp -s "$src" "$dst"; then
    return 0
  fi
  if [ -f "$dst" ]; then
    cp -p "$dst" "$key"
  else
    : > "$key.absent"
  fi
  install -o root -g root -m 644 "$src" "$dst"
  changed=1
}

restore_all() {
  local dst key
  for dst in "${FILES[@]}"; do
    key=$(backup_of "$dst")
    if [ -f "$key" ]; then
      install -o root -g root -m 644 "$key" "$dst"
    elif [ -f "$key.absent" ]; then
      rm -f "$dst"
    fi
  done
}

install_one "$WORK/out/monitor-traffic-filter.conf" "$CONF_D/monitor-traffic-filter.conf"
install_one "$WORK/out/tf-80.map" "$CONF_D/monitor-tf-80.map"
install_one "$WORK/out/tf-443.map" "$CONF_D/monitor-tf-443.map"
install_one "$WORK/out/cf.map" "$CONF_D/monitor-tf-cf.map"
install_one "$WORK/out/tf-exempt.map" "$CONF_D/monitor-tf-exempt.map"
install_one "$WORK/out/monitor-tf-80.conf" "$SNIPPETS/monitor-tf-80.conf"
install_one "$WORK/out/monitor-tf-443.conf" "$SNIPPETS/monitor-tf-443.conf"
install_one "$WORK/out/index.html" "$WWW/index.html"

if [ "$changed" = 0 ]; then
  # Do not exit early: a previous run may have installed the files and then
  # failed before reloading nginx, so the files on disk can be newer than the
  # running configuration. Re-validating and reloading makes the two converge
  # even when nothing was written this time.
  echo "monitor-nginx-tf: files unchanged (mode=$MODE); verifying"
fi

if ! nginx -t >"$WORK/nginx-t.log" 2>&1; then
  cat "$WORK/nginx-t.log" >&2
  restore_all
  echo "monitor-nginx-tf: nginx -t failed; previous files restored and nginx left running" >&2
  exit 2
fi

if ! systemctl reload nginx; then
  restore_all
  echo "monitor-nginx-tf: reload failed; previous files restored" >&2
  exit 2
fi

echo "monitor-nginx-tf: applied mode=$MODE"
